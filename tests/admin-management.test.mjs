test('new invite secret is generated by the API, hashed before RPC, and returned only once', async () => {
  calls.length = 0;
  const result = await management.createInvite({ mode: 'application', maxUses: 10, ttlSeconds: 3600, reason: '本学期社团招新活动请使用此邀请码' }, ctx(moderator));
  const call = calls[0];
  assert.equal(call.name, 'hg_admin_management');
  assert.equal(call.args.p_action, 'invites.create');
  assert.equal(call.args.p_actor_id, 'u_mod');
  assert.equal(call.args.p_input.code, undefined);
  assert.match(call.args.p_input.codeHash, /^[0-9a-f]{64}$/);
  assert.equal(crypto.createHash('sha256').update(result.code, 'utf8').digest('hex'), call.args.p_input.codeHash);
  assert.match(result.code, /^[A-F0-9]{32}$/);
  assert.equal(result.codeHash, undefined);
});

