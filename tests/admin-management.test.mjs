test('database recovery and term transition errors map to client-visible business responses', () => {
  for (const marker of ['TARGET_ACCEPTANCE_REQUIRED', 'RECOVERY_EXPIRED', 'RECOVERY_COOLDOWN', 'RECOVERY_SECOND_APPROVAL_REQUIRED']) {
    assert.equal(management.mapManagementError(new Error(marker)).kind, 'conflict');
  }
  assert.equal(management.mapManagementError(new Error('TEAM_INVALID')).kind, 'invalid_input');
  assert.equal(management.mapManagementError(new Error('MANAGEMENT_TERM_NOT_FOUND')).kind, 'not_accessible');
});
